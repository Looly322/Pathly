import { test, expect } from '@playwright/test';
const paris = { id:'1', name:'Paris',nameZh:'巴黎',regionZh:'法兰西岛',city:'Paris', country:'France',countryCode:'FR',region:'Île-de-France',latitude:48.85341,longitude:2.3488 };
const place = {id:'foursquare-test',source:'foursquare',sourceId:'test',name:'Test museum',latitude:48.85,longitude:2.35,categories:[{name:'Museum'}],address:'Paris',website:null,distance:200};
test('global destination confirmation, category search, errors and narrow layout', async ({page}) => {
  const requests=[];
  // 自动测试不访问公共瓦片服务；真实底图在可见浏览器中验证。
  await page.route('https://tiles.openfreemap.org/**',r=>r.fulfill({json:{version:8,sources:{},layers:[{id:'background',type:'background',paint:{'background-color':'#e9eeea'}}]}}));
  await page.route('https://tile.openstreetmap.org/**', r=>r.fulfill({contentType:'image/png',body:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAusB9Y9ZlS8AAAAASUVORK5CYII=','base64')}));
  await page.route('**/api/places/localize?*',r=>r.fulfill({json:{nameZh:'测试博物馆'}}));
  await page.route('**/api/destinations/search?*', r => r.fulfill({json:{destinations:[paris]}}));
  await page.route('**/api/places/search?*', r => { const url=new URL(r.request().url()); if(url.searchParams.get('radius')==='250') return r.fulfill({json:{places:[{...place,id:'nearby-place',name:'Nearby museum',address:'Verified address'}]}}); requests.push(url); return r.fulfill({json:{places:[place],queryUsed:''}}); });
  await page.goto('/');
  await page.getByRole('button',{name:'探索全球目的地',exact:true}).click();
  await page.getByLabel('旅行目的地',{exact:true}).fill('巴黎');
  await page.getByRole('button',{name:'查找城市',exact:true}).click();
  await page.getByRole('button',{name:/巴黎.*法国/}).click();
  await expect(page.locator('.global-place')).toContainText('Test museum');
  await expect(page.locator('.world-map-canvas')).toBeVisible();
  await expect(page.locator('.global-place h3')).toContainText('测试博物馆');
  await page.getByRole('button',{name:'在地图上查看',exact:true}).click();
  await expect(page.locator('.global-pin.active')).toHaveCount(1);
  await page.locator('.global-pin').click();
  await expect(page.locator('.global-place.selected')).toHaveCount(1);
  await page.getByRole('button',{name:'加入路线',exact:true}).click();
  await page.getByRole('button',{name:'我的路线 · 1',exact:true}).click();
  await expect(page.locator('.route-stop')).toContainText('测试博物馆');
  await page.locator('.world-map-canvas').click({position:{x:40,y:240}});
  await expect(page.getByText('选择这里的真实地点',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:/Nearby museum.*Verified address/}).click();
  await expect(page.getByLabel('给这个地点起个名字')).toHaveCount(0);
  await expect(page.locator('.route-stop')).toHaveCount(2);
  await expect(page.locator('.transit-legs a')).toHaveAttribute('href',/travelmode=transit/);
  await page.getByLabel('地图语言',{exact:true}).selectOption('en');
  await expect(page.getByLabel('地图语言',{exact:true})).toHaveValue('en');
  await page.getByRole('button',{name:'上移',exact:true}).last().click();
  await expect(page.locator('.route-stop').first()).toContainText('Nearby museum');
  await page.getByRole('button',{name:'删除',exact:true}).first().click();
  await expect(page.locator('.route-stop')).toHaveCount(1);
  await page.getByRole('button',{name:'发现景点',exact:true}).click();
  await page.getByLabel('地点分类'  ,{exact:true}).selectOption('museums');
  await expect.poll(()=>requests.length).toBe(2);
  expect(requests[1].searchParams.get('latitude')).toBe('48.85341');
  expect(requests[1].searchParams.get('category')).toBe('museums');
  await page.route('**/api/places/search?*',r=>r.fulfill({status:429,json:{error:'UPSTREAM_429'}}));
  await page.getByRole('button',{name:'搜索地点',exact:true}).click();
  await expect(page.getByRole('alert')).toContainText('额度');
  await expect(page.locator('.global-place')).toHaveCount(0);
  await page.setViewportSize({width:320,height:800});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('button',{name:'EN',exact:true}).click();
  await expect(page.locator('h1')).toHaveText('Paris · France');
});
